import type { Direction, IndustryKey, Won } from '@mintax/core';

/**
 * 로컬 휴리스틱 분류용 키워드 사전 (약 30개 계정).
 *
 * - 코드는 core 기본 계정과목표(DEFAULT_ACCOUNT_CODES) 기준이며, 후보 목록에 같은 코드가 없으면
 *   계정명(name → altNames 순)으로 후보를 찾는다. 사무소 코드체계(5자리 등)가 달라도 동작한다.
 * - 키워드는 전부 실무 관행 기반 추론값이다 [추론·검증필요]. core 시스템 사전(system_rule, 상한 90)보다
 *   약한 신호이므로 이 사전의 신뢰도 상한은 70 이다.
 * - '^' 로 시작하는 키워드는 상호(정규화) 앞부분 일치만 본다. 영문으로 끝나면 바로 뒤가 영문이 아니어야 한다
 *   ('^KT' 는 'KT강남' 은 맞지만 'KTX' 는 아님). '$' 로 끝나는 키워드는 상호 끝부분 일치 ('CC$').
 */
export interface HeuristicKeywordEntry {
  code: string;
  name: string;
  /** 후보에 name 이 없을 때 대신 찾을 계정명 */
  altNames?: string[];
  /** 기본 'purchase' */
  direction?: Direction;
  /** 상호·적요·가맹점업종 어디서든 포함되면 신호 */
  keywords: string[];
  /** 가맹점 업종 텍스트 전용 키워드 */
  categoryKeywords?: string[];
  /** 상호·적요에 이 단어가 있으면 이 계정 후보에서 제외 */
  exclude?: string[];
  /** 합계금액 범위 (즉시상각 기준 등) */
  minTotal?: Won;
  maxTotal?: Won;
  /** 이 업종이면 가산점 */
  boostIndustries?: IndustryKey[];
  /** 이 업종에서만 적용 */
  onlyIndustries?: IndustryKey[];
  /** 이 업종에서는 적용하지 않음 */
  skipIndustries?: IndustryKey[];
}

